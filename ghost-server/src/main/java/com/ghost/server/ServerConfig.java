package com.ghost.server;

import org.jetbrains.annotations.Nullable;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.SecureRandom;
import java.util.ArrayList;
import java.util.List;
import java.util.Properties;

/**
 * サーバー設定（ポート・バインドアドレス・パスワード・視認距離・レート制限・信頼済みプロキシ）の解決とバリデーションを担う不変レコード。
 * 優先順位: コマンドライン引数 &gt; server.properties &gt; デフォルト値
 */
public record ServerConfig(
        int port,
        String bindAddress,
        String password,
        double viewDistance,
        double rateLimit,
        List<String> trustedProxies,
        boolean passwordAutoGenerated
) {
    private static final Logger LOGGER = LoggerFactory.getLogger(ServerConfig.class);

    public static final int DEFAULT_PORT = 8887;
    public static final String DEFAULT_BIND_ADDRESS = "0.0.0.0";
    public static final double DEFAULT_VIEW_DISTANCE = 5 * 16.0; // 5 チャンク相当
    public static final double DEFAULT_RATE_LIMIT = 50.0;

    private static final String PASSWORD_ALPHABET =
            "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";
    private static final int GENERATED_PASSWORD_LENGTH = 16;
    private static final SecureRandom SECURE_RANDOM = new SecureRandom();

    public ServerConfig {
        if (port < 1 || port > 65535) {
            throw new IllegalArgumentException("Port must be between 1 and 65535: " + port);
        }
        if (bindAddress == null || bindAddress.isBlank()) {
            throw new IllegalArgumentException("Bind address must not be null or blank");
        }
        bindAddress = bindAddress.trim();
        if (password == null || password.isEmpty()) {
            throw new IllegalArgumentException("Password must not be null or empty");
        }
        if (viewDistance <= 0.0 || Double.isNaN(viewDistance) || Double.isInfinite(viewDistance)) {
            throw new IllegalArgumentException("View distance must be positive: " + viewDistance);
        }
        if (rateLimit <= 0.0 || Double.isNaN(rateLimit) || Double.isInfinite(rateLimit)) {
            throw new IllegalArgumentException("Rate limit must be positive: " + rateLimit);
        }
        trustedProxies = trustedProxies == null ? List.of() : List.copyOf(trustedProxies);
        ClientIpResolver.validateSpecs(trustedProxies);
    }

    /**
     * 設定ファイルを読み込みます。ファイルが存在しない場合は空の {@link Properties} を返します。
     */
    public static Properties loadProperties(Path configPath) {
        Properties props = new Properties();
        if (configPath != null && Files.exists(configPath)) {
            try (InputStream is = Files.newInputStream(configPath)) {
                props.load(is);
                LOGGER.info("Loaded configuration from {}", configPath);
            } catch (IOException e) {
                LOGGER.warn("Failed to load config file {}: {}", configPath, e.getMessage());
            }
        } else {
            LOGGER.info("Config file {} not found. Using defaults.", configPath);
        }
        return props;
    }

    /**
     * CLI 引数・Properties・デフォルト値から最終設定を解決します。
     */
    public static ServerConfig resolve(@Nullable Integer cliPort,
                                       @Nullable String cliBindAddress,
                                       @Nullable String cliPassword,
                                       @Nullable Double cliViewDistance,
                                       @Nullable Double cliRateLimit,
                                       @Nullable List<String> cliTrustedProxies,
                                       @Nullable Properties props) {
        Properties safeProps = props != null ? props : new Properties();

        int resolvedPort = cliPort != null ? cliPort
                : parsePortProperty(safeProps);

        String resolvedBindAddress = resolveBindAddress(cliBindAddress, safeProps);

        String resolvedPassword = (cliPassword != null && !cliPassword.isEmpty()) ? cliPassword
                : safeProps.getProperty("password");

        boolean autoGenerated = false;
        if (resolvedPassword == null || resolvedPassword.isEmpty()) {
            resolvedPassword = generateSecurePassword();
            autoGenerated = true;
        }

        double resolvedViewDistance = cliViewDistance != null ? cliViewDistance
                : parseDoubleProperty(safeProps, "view-distance", DEFAULT_VIEW_DISTANCE);

        double resolvedRateLimit = cliRateLimit != null ? cliRateLimit
                : parseDoubleProperty(safeProps, "rate-limit", DEFAULT_RATE_LIMIT);

        List<String> resolvedTrustedProxies = resolveTrustedProxies(cliTrustedProxies, safeProps);

        return new ServerConfig(
                resolvedPort,
                resolvedBindAddress,
                resolvedPassword,
                resolvedViewDistance,
                resolvedRateLimit,
                resolvedTrustedProxies,
                autoGenerated);
    }

    /**
     * {@link SecureRandom} を用いて推測困難なランダムパスワードを生成します。
     */
    public static String generateSecurePassword() {
        StringBuilder sb = new StringBuilder(GENERATED_PASSWORD_LENGTH);
        for (int i = 0; i < GENERATED_PASSWORD_LENGTH; i++) {
            int idx = SECURE_RANDOM.nextInt(PASSWORD_ALPHABET.length());
            sb.append(PASSWORD_ALPHABET.charAt(idx));
        }
        return sb.toString();
    }

    private static int parsePortProperty(Properties props) {
        String raw = props.getProperty("port");
        if (raw == null || raw.isBlank()) {
            return DEFAULT_PORT;
        }
        return Integer.parseInt(raw.trim());
    }

    private static String resolveBindAddress(@Nullable String cliBindAddress, Properties props) {
        if (cliBindAddress != null && !cliBindAddress.isBlank()) {
            return cliBindAddress.trim();
        }
        String propBind = props.getProperty("bind-address");
        if (propBind != null && !propBind.isBlank()) {
            return propBind.trim();
        }
        return DEFAULT_BIND_ADDRESS;
    }

    private static List<String> resolveTrustedProxies(@Nullable List<String> cliTrustedProxies, Properties props) {
        if (cliTrustedProxies != null) {
            return normalizeProxyList(cliTrustedProxies);
        }
        String raw = props.getProperty("trusted-proxies");
        if (raw == null || raw.isBlank()) {
            return List.of();
        }
        return normalizeProxyList(List.of(raw.split(",")));
    }

    private static List<String> normalizeProxyList(List<String> rawEntries) {
        List<String> result = new ArrayList<>();
        for (String entry : rawEntries) {
            if (entry != null) {
                String trimmed = entry.trim();
                if (!trimmed.isEmpty()) {
                    result.add(trimmed);
                }
            }
        }
        return List.copyOf(result);
    }

    private static double parseDoubleProperty(Properties props, String key, double defaultValue) {
        String raw = props.getProperty(key);
        if (raw == null || raw.isBlank()) {
            return defaultValue;
        }
        return Double.parseDouble(raw.trim());
    }
}
