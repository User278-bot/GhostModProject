package com.ghost.server;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Properties;

import static org.junit.jupiter.api.Assertions.*;

/**
 * {@link ServerConfig} の優先順位解決・バリデーション・安全なパスワード生成を検証するユニットテスト。
 */
class ServerConfigTest {

    @Test
    void resolve_PriorityOrder_CliOverridesPropertiesOverridesDefaults() {
        Properties props = new Properties();
        props.setProperty("port", "9000");
        props.setProperty("password", "prop-pass");
        props.setProperty("view-distance", "128.0");
        props.setProperty("rate-limit", "25.0");

        // CLI 未指定時は Properties の値が採用されること
        ServerConfig fromProps = ServerConfig.resolve(null, null, null, null, props);
        assertEquals(9000, fromProps.port());
        assertEquals("prop-pass", fromProps.password());
        assertEquals(128.0, fromProps.viewDistance());
        assertEquals(25.0, fromProps.rateLimit());
        assertFalse(fromProps.passwordAutoGenerated());

        // CLI 指定時は Properties を上書きすること
        ServerConfig fromCli = ServerConfig.resolve(7777, "cli-pass", 64.0, 100.0, props);
        assertEquals(7777, fromCli.port());
        assertEquals("cli-pass", fromCli.password());
        assertEquals(64.0, fromCli.viewDistance());
        assertEquals(100.0, fromCli.rateLimit());
        assertFalse(fromCli.passwordAutoGenerated());
    }

    @Test
    void resolve_DefaultsAndAutoGeneratedPassword() {
        ServerConfig config = ServerConfig.resolve(null, null, null, null, new Properties());

        assertEquals(ServerConfig.DEFAULT_PORT, config.port());
        assertEquals(ServerConfig.DEFAULT_VIEW_DISTANCE, config.viewDistance());
        assertEquals(ServerConfig.DEFAULT_RATE_LIMIT, config.rateLimit());
        assertTrue(config.passwordAutoGenerated());
        assertNotNull(config.password());
        assertEquals(16, config.password().length());
    }

    @Test
    void generateSecurePassword_ReturnsUnique16CharStrings() {
        String p1 = ServerConfig.generateSecurePassword();
        String p2 = ServerConfig.generateSecurePassword();

        assertEquals(16, p1.length());
        assertEquals(16, p2.length());
        assertNotEquals(p1, p2);
    }

    @Test
    void constructor_RejectsInvalidValues() {
        assertThrows(IllegalArgumentException.class,
                () -> new ServerConfig(0, "pass", 80.0, 50.0, false));
        assertThrows(IllegalArgumentException.class,
                () -> new ServerConfig(65536, "pass", 80.0, 50.0, false));
        assertThrows(IllegalArgumentException.class,
                () -> new ServerConfig(8887, "", 80.0, 50.0, false));
        assertThrows(IllegalArgumentException.class,
                () -> new ServerConfig(8887, "pass", 0.0, 50.0, false));
        assertThrows(IllegalArgumentException.class,
                () -> new ServerConfig(8887, "pass", 80.0, -1.0, false));
    }

    @Test
    void loadProperties_ReadsExistingFileAndHandlesMissingFile(@TempDir Path tempDir) throws Exception {
        Path existing = tempDir.resolve("server.properties");
        Files.writeString(existing, "port=9123\npassword=filepass\n");

        Properties loaded = ServerConfig.loadProperties(existing);
        assertEquals("9123", loaded.getProperty("port"));
        assertEquals("filepass", loaded.getProperty("password"));

        Properties missing = ServerConfig.loadProperties(tempDir.resolve("missing.properties"));
        assertTrue(missing.isEmpty());
    }
}
